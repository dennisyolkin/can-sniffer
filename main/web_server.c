#define PUSH_PERIOD_US (200 * 1000)
// The status goes out with every 5th frame table: once per second.
#define STATUS_EVERY_N_PUSHES 5
#define MAX_FRAMES 192
#define FRAMES_HEADER_LEN 8
#define FRAMES_MAGIC 'F'
#define FRAMES_VERSION 1
#define STATUS_JSON_MAX 512
// Commands from the page are short ("rec on", "mark <label>"); anything longer closes the connection.
#define MAX_INCOMING_LEN 64
#define MAX_CLIENTS CONFIG_LWIP_MAX_SOCKETS
// A phone that walks out of range must not stall the server for long.
#define SEND_TIMEOUT_S 2
// Off core 0, which belongs to the logger loop and the TWAI ISR.
#define SERVER_CORE 1

// Long enough for any real Accept-Encoding / If-None-Match value; longer ones are truncated, which only costs
// a missed 304 or a 406.
#define HEADER_BUF_LEN 128
// Hex characters of the firmware hash used as the ETag. 16 (64 bits) is plenty to tell builds apart.
#define ETAG_HASH_LEN 16

static const char *TAG = "web_server";

// Generated by the build from main/web/index.html (see main/CMakeLists.txt).
extern const uint8_t index_html_gz_start[] asm("_binary_index_html_gz_start");
extern const uint8_t index_html_gz_end[] asm("_binary_index_html_gz_end");

static httpd_handle_t server;
static esp_timer_handle_t push_timer;
static char etag[ETAG_HASH_LEN + 3];

// Only touched in the server's own task (handlers and queued work), so no locking.
static unsigned push_count;
static bool client_joined;
static uint8_t frames_buf[FRAMES_HEADER_LEN + MAX_FRAMES * sizeof(live_frame_t)];
static char status_buf[STATUS_JSON_MAX];

// Set by the timer, cleared by the work item: skips a tick instead of queueing work behind a slow send.
static atomic_bool push_pending;

static const char *const recorder_names[] = {
    [LIVE_RECORDER_NO_CARD] = "no_card",
    [LIVE_RECORDER_OFF] = "off",
    [LIVE_RECORDER_ON] = "on",
    [LIVE_RECORDER_FAILED] = "failed",
};

static bool header_contains(httpd_req_t *req, const char *field, const char *needle) {
    char value[HEADER_BUF_LEN];
    esp_err_t err = httpd_req_get_hdr_value_str(req, field, value, sizeof(value));
    if (err != ESP_OK && err != ESP_ERR_HTTPD_RESULT_TRUNC) {
        return false;
    }
    return strstr(value, needle) != NULL;
}

static esp_err_t index_get(httpd_req_t *req) {
    // "no-cache" means "store, but revalidate": the browser keeps the page and gets a body-less 304 until the
    // firmware changes. The ETag is the firmware's hash, so reflashing is what invalidates it.
    httpd_resp_set_hdr(req, "Cache-Control", "no-cache");
    httpd_resp_set_hdr(req, "ETag", etag);
    httpd_resp_set_hdr(req, "Vary", "Accept-Encoding");

    if (header_contains(req, "If-None-Match", etag)) {
        httpd_resp_set_status(req, "304 Not Modified");
        return httpd_resp_send(req, NULL, 0);
    }

    // Only the gzipped copy is stored. Every browser accepts gzip; curl needs --compressed.
    if (!header_contains(req, "Accept-Encoding", "gzip")) {
        httpd_resp_set_status(req, "406 Not Acceptable");
        httpd_resp_set_type(req, "text/plain");
        return httpd_resp_sendstr(req, "This page is only served gzip-compressed (e.g. curl --compressed).\n");
    }

    httpd_resp_set_type(req, "text/html; charset=utf-8");
    httpd_resp_set_hdr(req, "Content-Encoding", "gzip");
    return httpd_resp_send(req, (const char *) index_html_gz_start, index_html_gz_end - index_html_gz_start);
}

static size_t build_frames(void) {
    live_frame_t *entries = (live_frame_t *) (frames_buf + FRAMES_HEADER_LEN);
    size_t count = live_data_snapshot(entries, MAX_FRAMES);
    uint16_t count16 = count;
    uint32_t now_ms = (uint32_t) (esp_timer_get_time() / 1000);

    // Little-endian like the ESP32 itself, so the entries go out as they are in memory.
    frames_buf[0] = FRAMES_MAGIC;
    frames_buf[1] = FRAMES_VERSION;
    memcpy(&frames_buf[2], &count16, sizeof(count16));
    memcpy(&frames_buf[4], &now_ms, sizeof(now_ms));
    return FRAMES_HEADER_LEN + count * sizeof(live_frame_t);
}

static size_t build_status(size_t clients) {
    live_status_t s;
    live_data_get_status(&s);
    int len = snprintf(status_buf, sizeof(status_buf),
        "{\"type\":\"status\",\"uptime_ms\":%" PRIu32 ",\"fps\":%" PRIu32 ",\"frames\":%" PRIu32
        ",\"rx_dropped\":%" PRIu32 ",\"bus_errors\":%" PRIu32 ",\"bus_errors_per_s\":%" PRIu32
        ",\"rec\":\"%s\",\"session\":\"%s\",\"sd_dropped\":%" PRIu32 ",\"buffers_free\":%" PRIu32
        ",\"buffers\":%" PRIu32 ",\"marks\":%" PRIu32 ",\"clients\":%u,\"heap_free\":%u,\"heap_min\":%u}",
        (uint32_t) (esp_timer_get_time() / 1000), s.frames_per_s, s.frames_total, s.rx_dropped_total,
        s.bus_errors_total, s.bus_errors_per_s, recorder_names[s.recorder], s.session, s.sd_dropped,
        s.buffers_min_free, s.buffer_count, s.marks, (unsigned) clients,
        (unsigned) heap_caps_get_free_size(MALLOC_CAP_DEFAULT),
        (unsigned) heap_caps_get_minimum_free_size(MALLOC_CAP_DEFAULT));
    return len > 0 && len < (int) sizeof(status_buf) ? (size_t) len : 0;
}

static void send_all(const int *fds, size_t count, httpd_ws_type_t type, const void *payload, size_t len) {
    httpd_ws_frame_t frame = {
        .final = true,
        .type = type,
        .payload = (uint8_t *) payload,
        .len = len,
    };
    for (size_t i = 0; i < count; i++) {
        if (httpd_ws_send_frame_async(server, fds[i], &frame) != ESP_OK) {
            // Peer vanished without a close frame (e.g. phone left Wi-Fi range); free its socket now.
            httpd_sess_trigger_close(server, fds[i]);
        }
    }
}

// Runs in the server's task (via httpd_queue_work), so nothing else touches the sockets or the buffers meanwhile.
static void push(void *arg) {
    atomic_store(&push_pending, false);

    int fds[MAX_CLIENTS];
    size_t count = MAX_CLIENTS;
    if (httpd_get_client_list(server, &count, fds) != ESP_OK) {
        return;
    }
    size_t ws_count = 0;
    for (size_t i = 0; i < count; i++) {
        if (httpd_ws_get_fd_info(server, fds[i]) == HTTPD_WS_CLIENT_WEBSOCKET) {
            fds[ws_count++] = fds[i];
        }
    }
    if (ws_count == 0) {
        return;
    }

    send_all(fds, ws_count, HTTPD_WS_TYPE_BINARY, frames_buf, build_frames());

    // A new page gets the status (recording switch state) right away instead of within a second.
    push_count++;
    if (push_count % STATUS_EVERY_N_PUSHES == 0 || client_joined) {
        client_joined = false;
        size_t len = build_status(ws_count);
        if (len > 0) {
            send_all(fds, ws_count, HTTPD_WS_TYPE_TEXT, status_buf, len);
        }
    }
}

// esp_timer task: hand the work to the server's task rather than touching sockets from here.
static void on_push_timer(void *arg) {
    if (!atomic_exchange(&push_pending, true)) {
        if (httpd_queue_work(server, push, NULL) != ESP_OK) {
            atomic_store(&push_pending, false);
        }
    }
}

static void handle_command(const char *text) {
    if (strcmp(text, "rec on") == 0) {
        live_data_request_recording(true);
    } else if (strcmp(text, "rec off") == 0) {
        live_data_request_recording(false);
    } else if (strncmp(text, "mark ", 5) == 0) {
        if (live_data_add_mark(text + 5) != ESP_OK) {
            ESP_LOGW(TAG, "mark dropped: queue full");
        }
    } else {
        ESP_LOGW(TAG, "unknown command \"%s\"", text);
    }
}

static esp_err_t ws_handler(httpd_req_t *req) {
    if (req->method == HTTP_GET) {
        // Handshake done; from now on push() finds this socket in the client list.
        client_joined = true;
        return ESP_OK;
    }

    // The payload has to be consumed even when ignored, or the next frame would be parsed from its middle.
    // Control frames (ping, close) are answered by the server itself.
    httpd_ws_frame_t frame = {0};
    ESP_RETURN_ON_ERROR(httpd_ws_recv_frame(req, &frame, 0), TAG, "recv frame header");
    if (frame.len == 0) {
        return ESP_OK;
    }
    if (frame.len > MAX_INCOMING_LEN) {
        // Returning an error makes the server close the connection.
        return ESP_ERR_INVALID_SIZE;
    }
    uint8_t buf[MAX_INCOMING_LEN + 1];
    frame.payload = buf;
    ESP_RETURN_ON_ERROR(httpd_ws_recv_frame(req, &frame, frame.len), TAG, "recv frame");
    if (frame.type == HTTPD_WS_TYPE_TEXT) {
        buf[frame.len] = '\0';
        handle_command((const char *) buf);
    }
    return ESP_OK;
}

esp_err_t web_server_start(void) {
    ESP_RETURN_ON_FALSE(server == NULL, ESP_ERR_INVALID_STATE, TAG, "already started");

    char hash[ETAG_HASH_LEN + 1];
    esp_app_get_elf_sha256(hash, sizeof(hash));
    snprintf(etag, sizeof(etag), "\"%s\"", hash);

    httpd_config_t cfg = HTTPD_DEFAULT_CONFIG();
    cfg.core_id = SERVER_CORE;
    cfg.send_wait_timeout = SEND_TIMEOUT_S;
    // Phones reconnect often (screen off, app switch); reuse the oldest socket instead of refusing new ones.
    cfg.lru_purge_enable = true;
    ESP_RETURN_ON_ERROR(httpd_start(&server, &cfg), TAG, "httpd_start");

    static const httpd_uri_t index_route = {.uri = "/", .method = HTTP_GET, .handler = index_get};
    static const httpd_uri_t ws_route = {
        .uri = "/ws",
        .method = HTTP_GET,
        .handler = ws_handler,
        .is_websocket = true,
    };
    esp_err_t err = httpd_register_uri_handler(server, &index_route);
    if (err == ESP_OK) {
        err = httpd_register_uri_handler(server, &ws_route);
    }

    const esp_timer_create_args_t timer_args = {.callback = on_push_timer, .name = "ws_push"};
    if (err == ESP_OK) {
        err = esp_timer_create(&timer_args, &push_timer);
    }
    if (err == ESP_OK) {
        err = esp_timer_start_periodic(push_timer, PUSH_PERIOD_US);
    }
    if (err != ESP_OK) {
        if (push_timer != NULL) {
            esp_timer_delete(push_timer);
            push_timer = NULL;
        }
        httpd_stop(server);
        server = NULL;
        ESP_LOGE(TAG, "start failed: %s", esp_err_to_name(err));
        return err;
    }

    ESP_LOGI(TAG, "listening on port %d", cfg.server_port);
    return ESP_OK;
}
